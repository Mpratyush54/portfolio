const mongoose = require('mongoose');
const milestone = new mongoose.Schema(
  {
    label: String,
    percent: Number,
    timing: { type: String, enum: ['before', 'after'] },
    amountPaise: Number,
    releasedAt: Date,
    evidence: String,
    approvedAt: Date,
    feedback: String,
    orderId: String,
    orderAmountPaise: Number,
    collectionPaise: Number,
    collections: [{ amountPaise: Number, reason: String, at: Date, _id: false }],
    payments: [{ orderId: String, paymentId: String, amountPaise: Number, at: Date, _id: false }],
    orderBusy: Boolean,
    orderLock: String,
    orderLockedAt: Date,
    paymentId: String,
    paidAt: Date,
  },
  { _id: false },
);
const schema = new mongoose.Schema(
  {
    title: String,
    clientName: String,
    clientEmail: String,
    seller: String,
    builder: mongoose.Schema.Types.Mixed,
    draftEditor: mongoose.Schema.Types.Mixed,
    draftReady: Boolean,
    draftValidation: String,
    clientDraftId: { type: String, unique: true, sparse: true },
    lastDraftMutation: String,
    srs: [
      {
        fileId: mongoose.Schema.Types.ObjectId,
        name: String,
        mime: String,
        size: Number,
        sha256: String,
        uploadedAt: Date,
        _id: false,
      },
    ],
    scope: String,
    exclusions: String,
    timeline: String,
    terms: String,
    totalPaise: Number,
    minimumOnboardingPaise: Number,
    currency: { type: String, default: 'INR' },
    revision: { type: Number, default: 1 },
    previousId: mongoose.Schema.Types.ObjectId,
    status: {
      type: String,
      enum: ['draft', 'invited', 'accepted', 'cancelled'],
      default: 'draft',
    },
    validUntil: Date,
    tokenHash: { type: String, index: true, unique: true, sparse: true },
    tokenExpiresAt: Date,
    acceptance: {
      name: String,
      email: String,
      at: Date,
      digest: String,
      version: Number,
      acknowledgements: [String],
    },
    milestones: [milestone],
    deployedAt: Date,
    supportEndsAt: Date,
  },
  { timestamps: true, optimisticConcurrency: true },
);
schema.index({ status: 1, updatedAt: -1, _id: -1 });
schema.index({ updatedAt: -1, _id: -1 });
module.exports = mongoose.model('Quotation', schema);
